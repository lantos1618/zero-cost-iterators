#!/usr/bin/env python3
"""Emitter (TRUSTED, unverified): one IR JSON -> prog.bend (the term the Bend laws quantify over)
and i8dot.c (the native kernel). Usage: gen.py ir/<v>.json OUTDIR"""
import json, sys, os

C_OP = {  # one IR op -> C statement(s), all on int32_t scalars r0, r1, acc
    "LdA": ["r0 = (int32_t)a[i];"],
    "LdB": ["r1 = (int32_t)b[i];"],
    "Mul": ["r0 = r0 * r1;"],
    "Acc": ["acc = acc + r0;"],
    "Wrap": ["acc = (int32_t)((uint32_t)acc & 0xFFu);", "if (acc > 127) acc = acc - 256;"],
    "StT": ["t[i] = r0;"],
    "LdT": ["r0 = t[i];"],
    "Sub": ["r0 = r0 - r1;"],
    "Abs": ["if (r0 < 0) r0 = -r0;"],
    "Sq": ["r0 = r0 * r0;"],
    "Pos": ["if (r0 < 0) r0 = 0;"],
    "Bit": ["if (r0 > 0) r0 = 1;"],
    "AbsT": ["r0 = r0 < 0 ? -r0 : r0;"],
    "Ne0": ["r0 = r0 != 0;"],
}

def bend_term(prog):
    def ops(l):
        return "K.ONil{}" if not l else "K.OCons{K.%s{}, %s}" % (l[0], ops(l[1:]))
    def stmts(l):
        if not l:
            return "K.PNil{}"
        s = "K.Alloc{}" if l[0] == "alloc" else "K.Loop{%s}" % ops(l[0]["loop"])
        return "K.PCons{%s, %s}" % (s, stmts(l[1:]))
    return stmts(prog)

def c_text(name, prog, max_n):
    alloc = any(s == "alloc" for s in prog)
    L = ["/* emitted by gen.py from ir/%s.json -- do not edit */" % name,
         "#include <stddef.h>", "#include <stdint.h>"]
    if alloc:
        L.append("#include <stdlib.h>")
    L += ["#define I8DOT_MAX_N %du" % max_n, "",
          "int i8dot(const int8_t *a, const int8_t *b, size_t n, int32_t *out) {",
          "  if (n > I8DOT_MAX_N) return -1;",
          "  int32_t acc = 0;", "  int32_t r0 = 0;", "  int32_t r1 = 0;"]
    for s in prog:
        if s == "alloc":
            L += ["  int32_t *t = (int32_t *)malloc((n ? n : 1) * sizeof(int32_t));",
                  "  if (!t) return -2;"]
            continue
        L.append("  for (size_t i = 0; i < n; i++) {")
        for op in s["loop"]:
            L += ["    " + c for c in C_OP[op]]
        L.append("  }")
    if alloc:
        L.append("  free(t);")
    L += ["  *out = acc;", "  return 0;", "}", ""]
    return "\n".join(L)

def main():
    src, out = sys.argv[1], sys.argv[2]
    ir = json.load(open(src))
    os.makedirs(out, exist_ok=True)
    with open(os.path.join(out, "prog.bend"), "w") as f:
        f.write("import Base\nimport ./kernel.bend as K\n\n# generated by gen.py from %s -- do not edit\n"
                "def prog() -> K.Stmts:\n  %s\n" % (src, bend_term(ir["prog"])))
    with open(os.path.join(out, "i8dot.c"), "w") as f:
        f.write(c_text(ir["name"], ir["prog"], int(ir.get("max_n", 131071))))

if __name__ == "__main__":
    main()
